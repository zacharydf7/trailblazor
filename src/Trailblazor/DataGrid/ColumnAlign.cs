namespace Trailblazor;

/// <summary>Where a <see cref="TbColumn{TItem}"/> places its header and cells.</summary>
public enum ColumnAlign
{
    /// <summary>At the start of the line, the usual place for text.</summary>
    Start,

    /// <summary>In the middle.</summary>
    Center,

    /// <summary>At the end of the line, so the digits of numbers line up.</summary>
    End,
}
