using System.Text;
using System.Text.RegularExpressions;

// Writes Trailblazor.Icons.Material's icon classes from an unpacked @material-symbols/svg-400 npm package:
// dotnet run --project tools/Trailblazor.Icons.Generator -- <package folder> src/Trailblazor.Icons.Material
if (args.Length != 2)
{
    Console.Error.WriteLine("Usage: <unpacked @material-symbols/svg-400 package folder> <output folder>");
    return 1;
}

var (package, output) = (args[0], args[1]);
var version = Regex.Match(File.ReadAllText(Path.Combine(package, "package.json")), "\"version\": \"([^\"]+)\"")
    .Groups[1].Value;

foreach (var style in new[] { "Outlined", "Rounded", "Sharp" })
{
    var folder = Path.Combine(package, style.ToLowerInvariant());
    var names = Directory.GetFiles(folder, "*.svg").Select(Path.GetFileNameWithoutExtension)
        .Where(name => !name!.EndsWith("-fill", StringComparison.Ordinal)).Order(StringComparer.Ordinal).ToList();
    var plain = new StringBuilder();
    var filled = new StringBuilder();
    foreach (var name in names)
    {
        var path = PathOf(Path.Combine(folder, $"{name}.svg"));
        var filledPath = PathOf(Path.Combine(folder, $"{name}-fill.svg"));
        var property = PropertyName(name!);
        plain.AppendLine($"        public static Icon {property} => new(\"<path d=\\\"{path}\\\" />\", ViewBox);");
        filled.AppendLine(filledPath == path
            ? $"        public static Icon {property} => {style}.{property};"
            : $"        public static Icon {property} => new(\"<path d=\\\"{filledPath}\\\" />\", ViewBox);");
    }

    Write(style, $"Material Symbols in the {style} style.", plain);
    Write($"{style}Filled", $"Material Symbols in the {style} style, filled.", filled);
}

return 0;

// Every icon in the package is one path on the same 960-unit grid.
static string PathOf(string file)
{
    var svg = File.ReadAllText(file);
    var paths = Regex.Matches(svg, "<path d=\"([^\"]+)\"/>");
    if (paths.Count != 1 || !svg.Contains("viewBox=\"0 -960 960 960\"", StringComparison.Ordinal))
    {
        throw new InvalidOperationException($"{file} isn't a single path on the 960-unit grid.");
    }

    return paths[0].Groups[1].Value;
}

// add_circle becomes AddCircle, and 10k becomes _10k, since a name can't start with a digit.
static string PropertyName(string name)
{
    var pascal = string.Concat(name.Split('_').Select(word => char.ToUpperInvariant(word[0]) + word[1..]));
    return char.IsDigit(pascal[0]) ? $"_{pascal}" : pascal;
}

void Write(string className, string summary, StringBuilder properties)
{
    var file = new StringBuilder()
        .AppendLine("// <auto-generated>")
        .AppendLine($"// Made by tools/Trailblazor.Icons.Generator from @material-symbols/svg-400 {version}.")
        .AppendLine("// </auto-generated>")
        .AppendLine("#pragma warning disable CS1591")
        .AppendLine()
        .AppendLine("namespace Trailblazor.Icons.Material;")
        .AppendLine()
        .AppendLine("public static partial class MaterialSymbols")
        .AppendLine("{")
        .AppendLine($"    /// <summary>{summary}</summary>")
        .AppendLine($"    public static class {className}")
        .AppendLine("    {")
        .Append(properties)
        .AppendLine("    }")
        .AppendLine("}");
    File.WriteAllText(Path.Combine(output, $"MaterialSymbols.{className}.g.cs"), file.ToString());
}
